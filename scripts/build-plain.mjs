// Rebuilds the plain-text version of the home page inside public/burnsos.html.
//
// The home page is an interactive computer drawn by script. Search engines, screen readers and anyone with scripts
// off need the same content as ordinary HTML. This writes it between the two "plain" markers, from the very data the
// computer uses, so the two can never drift apart. Run:  node scripts/build-plain.mjs          (rewrite the file)
//                                                        node scripts/build-plain.mjs --check  (exit 1 if out of date)
import fs from "node:fs";
import { fileURLToPath } from "node:url";

const file = fileURLToPath(new URL("../public/burnsos.html", import.meta.url));
const START = "<!-- plain:start (generated by scripts/build-plain.mjs; do not edit by hand) -->", END = "<!-- plain:end -->";
const esc = (t) => String(t).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));
const strip = (t) => t.replace(/<[^>]+>/g, "").replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/\s+/g, " ").trim();

export function buildPlain(html) {
  const literal = (name, open, close) => { const a = html.indexOf(`const ${name} = ${open}`); if (a < 0) throw new Error(`${name} not found`); const from = a + `const ${name} = `.length, to = html.indexOf(`\n${close};`, from) + 1 + close.length; return (0, eval)(`(${html.slice(from, to)})`); };
  const P = literal("P", "[", "]"), ABOUT = literal("ABOUT", "{", "}");
  const between = (a, b) => { const i = html.indexOf(a); if (i < 0) throw new Error(`marker not found: ${a}`); return html.slice(i, html.indexOf(b, i)); };
  const about = [...between('} else if (f.name === "about") {', '} else if (f.name === "timeline") {').matchAll(/<p>([\s\S]*?)<\/p>/g)].map((m) => strip(m[1]));
  const principles = [...between('if (f.name === "principles") return `', '  if (f.name === "timeline") return').matchAll(/<span class="b">\d\d\s+([^<]+)<\/span>\\n([\s\S]*?)(?=\\n\\n|`;)/g)].map((m) => [strip(m[1]), strip(m[2].replace(/\\n/g, " "))]);
  if (P.length < 9 || about.length < 3 || principles.length < 5) throw new Error(`unexpected content: ${P.length} projects, ${about.length} about paragraphs, ${principles.length} principles`);
  const project = (p) => `    <article>
      <h3>${esc(p.name)}</h3>
      <p>${esc(p.cat)}, ${esc(p.period)}. ${esc(p.tag)}</p>
      <p>${esc(ABOUT[p.slug])}</p>
      <ul>${p.out.map((o) => `<li>${esc(o)}</li>`).join("")}</ul>
      <p>Built with ${esc(p.stack.join(", "))}.${p.links.map((l) => ` <a href="${esc(l[1])}">${esc(l[0])}</a>.`).join("")}</p>
    </article>`;
  return `${START}
<section class="plain" id="plain" aria-label="Plain-text version of this site">
  <h1>Dylan Burns</h1>
  <p>Passionate technologist and explorer.</p>
  <noscript><p>This site is normally an interactive vintage computer, which needs JavaScript. With scripts off, everything on it is written out below.</p></noscript>
  <h2>About</h2>
${about.map((t) => `  <p>${esc(t)}</p>`).join("\n")}
  <h2>Projects</h2>
${P.map(project).join("\n")}
  <h2>Principles</h2>
  <ol>
${principles.map(([t, n]) => `    <li><strong>${esc(t)}.</strong> ${esc(n)}</li>`).join("\n")}
  </ol>
  <h2>Contact</h2>
  <p><a href="mailto:dylanburns1524@gmail.com">dylanburns1524@gmail.com</a>, <a href="https://github.com/Dylan-Burns">GitHub</a>, <a href="https://www.linkedin.com/in/dylan-burns-">LinkedIn</a>.</p>
</section>
${END}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const html = fs.readFileSync(file, "utf8"), a = html.indexOf(START), b = html.indexOf(END);
  if (a < 0 || b < 0) { console.error("plain markers not found in public/burnsos.html"); process.exit(1); }
  const next = html.slice(0, a) + buildPlain(html) + html.slice(b + END.length);
  if (process.argv.includes("--check")) { if (next !== html) { console.error("plain-text version is out of date: run `node scripts/build-plain.mjs`"); process.exit(1); } console.log("plain-text version is up to date"); }
  else { fs.writeFileSync(file, next); console.log(next === html ? "plain-text version already up to date" : "plain-text version rewritten"); }
}
